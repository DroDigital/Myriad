/// The font as 128 glyphs x 7 rows; each row's low 5 bits are its pixels,
/// bit 4 = leftmost. Unknown characters are blank.
pub fn packed() -> Vec<u32> {
    let mut out = vec![0u32; 128 * ROWS];
    let mut put = |code: usize, rows: [&str; ROWS]| {
        for (r, row) in rows.iter().enumerate() {
            let bits = row
                .chars()
                .fold(0u32, |acc, c| (acc << 1) | u32::from(c == '#'));
            out[code * ROWS + r] = bits;
        }
    };
    for &(ch, rows) in GLYPHS {
        put(ch as usize, rows);
    }
    put(BLOCK as usize, ["#####"; ROWS]);
    out
}

/// Glyph index for a character (lowercase maps to uppercase; unknown -> space).
pub fn glyph(c: char) -> u32 {
    let c = c.to_ascii_uppercase();
    if c == '\u{2588}' {
        return BLOCK as u32;
    }
    if c.is_ascii() && (c == ' ' || GLYPHS.iter().any(|&(g, _)| g == c)) {
        c as u32
    } else {
        ' ' as u32
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_by_seven() {
        for &(ch, rows) in GLYPHS {
            for row in rows {
                assert_eq!(row.len(), COLS, "glyph {ch:?}");
                assert!(row.chars().all(|c| c == '#' || c == '.'), "glyph {ch:?}");
            }
        }
    }

    #[test]
    fn packing_and_lookup() {
        let font = packed();
        let a = 'A' as usize * ROWS;
        assert_eq!(font[a], 0b01110);
        assert_eq!(font[a + 3], 0b11111);
        assert!(font[' ' as usize * ROWS..][..ROWS].iter().all(|&r| r == 0));
        assert_eq!(glyph('a'), 'A' as u32);
        assert_eq!(glyph('~'), ' ' as u32);
        assert_eq!(glyph('\u{2588}'), BLOCK as u32);
    }
}
